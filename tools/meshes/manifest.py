#!/usr/bin/env python3
"""Write src/shared/Meshes.luau and assets/meshes/manifest.json from the
per-item meta.json files. Asset ids already in Meshes.luau are kept."""
import json
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
ASSETS = os.path.join(ROOT, "assets", "meshes")
LUAU = os.path.join(ROOT, "src", "shared", "Meshes.luau")
KEYS = ("model", "color", "normal", "roughness", "metalness", "emissive")
# Finish variants (tools/meshes/finishes.py): id key -> file in the item folder.
FINISH = {"satinR": "rough_satin", "metalR": "rough_metal", "metalM": "metal_metal", "glossR": "rough_gloss", "matteR": "rough_matte"}
SHELL = os.path.join(ROOT, "assets", "shell")
SURF = os.path.join(ROOT, "assets", "surfaces")
SURF_KEYS = ("color", "normal", "roughness")


def old_ids():
    ids = {}
    if not os.path.exists(LUAU):
        return ids
    cur = None
    for line in open(LUAU):
        m = re.match(r"\t(\w+) = \{$", line)
        if m:
            cur = m.group(1)
        m = re.match(r"\t\tids = \{(.*)\},", line)
        if m and cur:
            ids[cur] = {k: int(v) for k, v in re.findall(r"(\w+) = (\d+)", m.group(1))}
    return ids


def num(v):
    return ("%.4f" % v).rstrip("0").rstrip(".") if isinstance(v, float) else str(v)


def vec(v):
    return "{ " + ", ".join(num(float(x)) for x in v) + " }"


def entries_in(folder, keep, finishes):
    entries = []
    for item_id in sorted(os.listdir(folder)):
        meta_path = os.path.join(folder, item_id, "meta.json")
        if not os.path.isfile(meta_path):
            continue
        meta = json.load(open(meta_path))
        files = {k: os.path.exists(os.path.join(folder, item_id, k + ".png")) for k in KEYS[1:]}
        meta["files"] = [item_id + ".fbx"] + [k + ".png" for k in KEYS[1:] if files[k]]
        keys = list(KEYS)
        if finishes:
            for k, f in FINISH.items():
                if os.path.exists(os.path.join(folder, item_id, f + ".png")):
                    meta["files"].append(f + ".png")
                    keys.append(k)
        meta["ids"] = {k: keep.get(item_id, {}).get(k, 0) for k in keys}
        entries.append(meta)
    return entries


def entry_lines(e):
    out = ["\t%s = {" % e["id"], "\t\tsize = %s," % vec(e["size"]), "\t\tcenter = %s," % vec(e["center"]), "\t\ttris = %d," % e["tris"]]
    if e.get("light"):
        L = e["light"]
        parts = ["at = %s" % vec(L["at"]), "brightness = %s" % num(float(L["brightness"])), "range = %s" % num(float(L["range"]))]
        if L.get("color"):
            parts.append("color = %s" % vec(L["color"]))
        out.append("\t\tlight = { %s }," % ", ".join(parts))
    out.append("\t\tids = { %s }," % ", ".join("%s = %d" % (k, v) for k, v in e["ids"].items()))
    out.append("\t},")
    return out


def main():
    keep = old_ids()
    entries = entries_in(ASSETS, keep, True)
    shells = entries_in(SHELL, keep, False) if os.path.isdir(SHELL) else []
    surf_meta = json.load(open(os.path.join(SURF, "surfaces.json"))) if os.path.isdir(SURF) else {}
    surfaces = []
    for key in sorted(surf_meta):
        m = surf_meta[key]
        surfaces.append({"id": key, "variant": m["variant"], "base": m["base"], "studs": m["studs"],
                         "files": [k + ".png" for k in SURF_KEYS],
                         "ids": {k: keep.get(key, {}).get(k, 0) for k in SURF_KEYS}})
    json.dump({"refCell": 4.8, "items": entries, "shell": shells, "surfaces": surfaces},
              open(os.path.join(ASSETS, "manifest.json"), "w"), indent=1)
    out = [
        "--!strict",
        "-- Generated by tools/meshes/manifest.py from assets/{meshes,shell,surfaces}.",
        "-- Only the ids lines change by hand or by scripts/upload-meshes.luau.",
        "-- size and center are studs at Meshes.RefCell, engine axes, floor at y = 0,",
        "-- +Z is the front. An item uses its mesh once ids.model and ids.color are set.",
        "-- satinR/metalR/metalM/glossR/matteR are the Finish map variants.",
        "",
        "export type Light = { at: { number }, brightness: number, range: number, color: { number }? }",
        "export type Entry = { size: { number }, center: { number }, tris: number, ids: { [string]: number }, light: Light? }",
        "export type Surface = { variant: string, base: string, studs: number, ids: { [string]: number } }",
        "",
        "local Items: { [string]: Entry } = {",
    ]
    for e in entries:
        out += entry_lines(e)
    out += ["}", "", "-- Room shell pieces (curtains). Same rules as Items.", "local Shell: { [string]: Entry } = {"]
    for e in shells:
        out += entry_lines(e)
    out += ["}", "", "-- Floor and wall textures. variant is the MaterialVariant name in MaterialService;", "-- ids are Image assets for Texture overlays when no variant is saved there.", "local Surfaces: { [string]: Surface } = {"]
    for e in surfaces:
        out.append("\t%s = {" % e["id"])
        out.append('\t\tvariant = "%s",' % e["variant"])
        out.append('\t\tbase = "%s",' % e["base"])
        out.append("\t\tstuds = %d," % e["studs"])
        out.append("\t\tids = { %s }," % ", ".join("%s = %d" % (k, v) for k, v in e["ids"].items()))
        out.append("\t},")
    out += ["}", "", "return {", "\tRefCell = 4.8,", "\tItems = Items,", "\tShell = Shell,", "\tSurfaces = Surfaces,", "}", ""]
    open(LUAU, "w").write("\n".join(out))
    print("wrote", LUAU, len(entries), "items", len(shells), "shell", len(surfaces), "surfaces")


if __name__ == "__main__":
    main()
