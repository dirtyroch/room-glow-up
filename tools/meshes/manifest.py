#!/usr/bin/env python3
"""Write src/shared/Meshes.luau and assets/meshes/manifest.json from the
per-item meta.json files. Asset ids already in Meshes.luau are kept."""
import json
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
ASSETS = os.path.join(ROOT, "assets", "meshes")
LUAU = os.path.join(ROOT, "src", "shared", "Meshes.luau")
KEYS = ("model", "color", "normal", "roughness", "metalness", "emissive")


def old_ids():
    ids = {}
    if not os.path.exists(LUAU):
        return ids
    cur = None
    for line in open(LUAU):
        m = re.match(r"\t(\w+) = \{$", line)
        if m:
            cur = m.group(1)
        m = re.match(r"\t\tids = \{(.*)\},", line)
        if m and cur:
            ids[cur] = {k: int(v) for k, v in re.findall(r"(\w+) = (\d+)", m.group(1))}
    return ids


def num(v):
    return ("%.4f" % v).rstrip("0").rstrip(".") if isinstance(v, float) else str(v)


def vec(v):
    return "{ " + ", ".join(num(float(x)) for x in v) + " }"


def main():
    keep = old_ids()
    entries = []
    for item_id in sorted(os.listdir(ASSETS)):
        meta_path = os.path.join(ASSETS, item_id, "meta.json")
        if not os.path.isfile(meta_path):
            continue
        meta = json.load(open(meta_path))
        files = {k: os.path.exists(os.path.join(ASSETS, item_id, k + ".png")) for k in KEYS[1:]}
        meta["files"] = [item_id + ".fbx"] + [k + ".png" for k in KEYS[1:] if files[k]]
        meta["ids"] = {k: keep.get(item_id, {}).get(k, 0) for k in KEYS}
        entries.append(meta)
    json.dump({"refCell": 4.8, "items": entries}, open(os.path.join(ASSETS, "manifest.json"), "w"), indent=1)
    out = [
        "--!strict",
        "-- Generated by tools/meshes/manifest.py from assets/meshes/*/meta.json.",
        "-- Only the ids lines change by hand or by scripts/upload-meshes.luau.",
        "-- size and center are studs at Meshes.RefCell, engine axes, floor at y = 0,",
        "-- +Z is the front. An item uses its mesh once ids.model and ids.color are set.",
        "",
        "export type Ids = { model: number, color: number, normal: number, roughness: number, metalness: number, emissive: number }",
        "export type Light = { at: { number }, brightness: number, range: number, color: { number }? }",
        "export type Entry = { size: { number }, center: { number }, tris: number, ids: Ids, light: Light? }",
        "",
        "local Items: { [string]: Entry } = {",
    ]
    for e in entries:
        out.append("\t%s = {" % e["id"])
        out.append("\t\tsize = %s," % vec(e["size"]))
        out.append("\t\tcenter = %s," % vec(e["center"]))
        out.append("\t\ttris = %d," % e["tris"])
        if e.get("light"):
            L = e["light"]
            parts = ["at = %s" % vec(L["at"]), "brightness = %s" % num(float(L["brightness"])), "range = %s" % num(float(L["range"]))]
            if L.get("color"):
                parts.append("color = %s" % vec(L["color"]))
            out.append("\t\tlight = { %s }," % ", ".join(parts))
        out.append("\t\tids = { %s }," % ", ".join("%s = %d" % (k, e["ids"][k]) for k in KEYS))
        out.append("\t},")
    out += ["}", "", "return {", "\tRefCell = 4.8,", "\tItems = Items,", "}", ""]
    open(LUAU, "w").write("\n".join(out))
    print("wrote", LUAU, len(entries), "items")


if __name__ == "__main__":
    main()
